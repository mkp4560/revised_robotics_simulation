EMPIRICAL_COLONY_SIZES = [54, 56, 57, 68, 73, 76, 79, 90, 92, 110, 130, 160]

def run_parameterized_abm(
    colony_size: int,
    seed: int,
    single_lane: bool = True,
    p_so: float = 0.30,
    p_lfr: float = 1.00,
    tr_jam_sec: float = 9.0,
    rho_jam: float = 0.008,
) -> dict:
    """
    Execute Joy D. Bairagya's exact original ABM script (joy_Trafic_jam_Single-lane.py
    or joy_Trafic_jam_Multi-lane.py) in an isolated namespace with deterministic RNG seed.
    """
    import io, contextlib
    if single_lane:
        script_file = "joy_Trafic_jam_Single-lane.py" if os.path.exists("joy_Trafic_jam_Single-lane.py") else "abm_single_lane.py"
    else:
        script_file = "joy_Trafic_jam_Multi-lane.py" if os.path.exists("joy_Trafic_jam_Multi-lane.py") else "abm_multi_lane.py"
    with open(script_file, "r") as f:
        code = f.read()

    # Override colony size, 1 replicate, seed, and knockout parameters (prob_lost_taken = p_lfr, probability_lost = 1 - p_so)
    code = code.replace("num_sim = 1 if _args.quick else _args.num_sims", "num_sim = 1")
    code = code.replace(
        "Lost_taken = np.array([76]) if _args.quick else (np.array([_args.colony_size]) if _args.colony_size else np.array([54,56,57,68,73,76,79,90,92,110,130,160]))",
        f"Lost_taken = np.array([{int(colony_size)}])"
    )
    code = code.replace("np.random.seed(42 + int(number_ant) * 100 + i5)", f"np.random.seed({int(seed)})")
    code = code.replace("prob_lost_taken=1", f"prob_lost_taken={float(p_lfr)}")
    code = code.replace("probability_lost=0.7", f"probability_lost={float(1.0 - p_so)}")
    code = code.replace("prob_back_jam=0.008", f"prob_back_jam={float(rho_jam)}")
    code = code.replace("T=np.linspace(0,49,5000)", "T=np.linspace(0,49,2700)")
    # Suppress file writes inside worker processes
    code = code.replace("np.savetxt(", "# np.savetxt(")
    code = code.replace("_df_out.to_csv(", "# _df_out.to_csv(")

    ns = {}
    with contextlib.redirect_stdout(io.StringIO()), np.errstate(divide="ignore", invalid="ignore"):
        exec(code, ns)

    t_sec = float(ns["Avarge_time_required"][0]) if len(ns["Time_required"]) > 0 else 2700.0
    jams = float(ns["Avarage_Jaming"][0]) if len(ns["Jamming"]) > 0 else float(ns.get("Total_Jam", 0))
    inter = float(ns["Avarage_Interuption"][0]) if len(ns["Interpution"]) > 0 else float(ns.get("Total_interruption", 0))
    mr_so_pct = float(ns["Num_switovr_aray"][0]) if np.isfinite(ns["Num_switovr_aray"][0]) else 0.0
    mr_lf_pct = float(ns["Num_MR_array"][0]) if np.isfinite(ns["Num_MR_array"][0]) else 0.0

    return {
        "colony_size": int(colony_size),
        "completed": len(ns["Time_required"]) > 0,
        "transport_time_min": round(t_sec / 60.0, 3),
        "transport_time_sec": round(t_sec, 1),
        "total_interruptions": round(inter, 2),
        "total_jams": round(jams, 2),
        "mr_so_events": int(ns.get("Total_swtovr", 0)),
        "mr_lf_events": int(ns.get("Total_MR", 0)),
        "mr_so_pct": round(mr_so_pct, 2),
        "mr_lf_pct": round(mr_lf_pct, 2),
        "total_mr_pct": round(mr_so_pct + mr_lf_pct, 2),
    }


def _abm_worker(args_tuple):
    c_size, seed, single_lane, p_so, p_lfr, tr_j, rho_j, label = args_tuple
    res = run_parameterized_abm(c_size, seed, single_lane, p_so, p_lfr, tr_j, rho_j)
    res["condition"] = label
    res["p_so"] = p_so
    res["p_lfr"] = p_lfr
    res["tr_jam_sec"] = tr_j
    res["rho_jam"] = rho_j
    return res


