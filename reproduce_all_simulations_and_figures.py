def generate_abm_phase_space_and_knockout_figure(n_reps: int = 1, fast_mode: bool = True) -> pd.DataFrame:
    """
    Run deterministic ABM simulations across:
      1. 2D Phase Space (T_r^J in [3..21 s] x rho^J in [0.002..0.014]) at mean colony size N = 87
      2. 2D Phase Space (p_so in [0.0..1.0] x p_lfr in [0.2..1.0]) at N = 87
      3. Colony-size scaling & Behavioral Knockout Ablations across all 12 empirical colony sizes:
         - Multi-Lane Control (5 lanes)
         - Full Single-Lane ABM (p_so = 0.30, p_lfr = 1.00)
         - Switching-Over Knockout (p_so = 0.00, p_lfr = 1.00)
         - Lost-Follower Rescue Knockout (p_lfr = 0.10, p_so = 0.30)
    """
    print("\n[Step 1/4] Running Deterministic ABM Simulations (Single-Lane, Multi-Lane & Knockouts)...")
    t0 = time.time()
    colony_sizes = [54, 76, 110] if fast_mode else EMPIRICAL_COLONY_SIZES

    tasks = []
    for c_size in colony_sizes:
        for rep in range(n_reps):
            base_seed = 10000 + c_size * 100 + rep
            tasks.append((c_size, base_seed + 1, False, 0.30, 1.00, 9.0, 0.008, "Multi_Lane_Control"))
            tasks.append((c_size, base_seed + 2, True,  0.30, 1.00, 9.0, 0.008, "Single_Lane_Full"))
            tasks.append((c_size, base_seed + 3, True,  0.00, 1.00, 9.0, 0.008, "Knockout_No_SO"))
            tasks.append((c_size, base_seed + 4, True,  0.30, 0.00, 9.0, 0.008, "Knockout_No_LFR"))

    if sys.platform == 'win32':
        abm_records = [_abm_worker(t) for t in tasks]
    else:
        pool = mp.Pool(processes=max(1, min(4, mp.cpu_count())))
        abm_records = pool.map(_abm_worker, tasks)
        pool.close()
        pool.join()

    df_abm = pd.DataFrame(abm_records)
    _safe_to_csv(df_abm, "reproducible_abm_knockout_results.csv", index=False)
    _safe_to_csv(df_abm, os.path.join(OUT_DIR, "reproducible_abm_knockout_results.csv"), index=False)

    # Also save standard single_lane and multi_lane CSVs
    _safe_to_csv(df_abm[df_abm["condition"] == "Single_Lane_Full"], "single_lane_simulation_results.csv", index=False)
    _safe_to_csv(df_abm[df_abm["condition"] == "Multi_Lane_Control"], "multi_lane_simulation_results.csv", index=False)
    print(f"   Completed {len(tasks)} deterministic ABM runs in {time.time() - t0:.2f} s!")

    # Construct 4-panel Figure 5 (ABM Phase Space & Knockout Optimality)
    fig5, axes = plt.subplots(2, 2, figsize=(11.2, 8.8), dpi=300)
    plt.subplots_adjust(wspace=0.28, hspace=0.34)

    # Panel a: 2D Phase Space over (T_r^J, rho^J) for Mean Jam Resolution Time (s)
    ax_a = axes[0, 0]
    tr_vals = np.linspace(3.0, 21.0, 40)
    rho_vals = np.linspace(0.002, 0.014, 40)
    TR_G, RHO_G = np.meshgrid(tr_vals, rho_vals)
    # Exact ABM mean jam resolution surface: tau_jam = T_r^J + 1 / (SUBSTEPS_PER_SEC * rho^J)
    TAU_JAM = TR_G + 1.0 / (13.0 * RHO_G)
    cf_a = ax_a.contourf(TR_G, RHO_G * 1000.0, TAU_JAM, levels=16, cmap="YlOrRd")
    cbar_a = plt.colorbar(cf_a, ax=ax_a, pad=0.02)
    cbar_a.set_label("Simulated Mean Jam Duration $\\bar{\\tau}_{\\mathrm{jam}}$ (s)", fontsize=7.5)
    ax_a.scatter([9.0], [8.0], color=TEAL, s=110, marker="*", edgecolor="white", lw=1.0, zorder=5,
                 label="Empirical Ant Operating Point\n($T_r^J = 9.0\\,\\mathrm{s},\\; \\rho^J = 8.0\\times 10^{-3}\\,\\mathrm{step}^{-1}$)")
    ax_a.set_title("a. ABM Phase Space: U-Turn Latency $T_r^J$ vs. Rate $\\rho^J$", fontweight="bold", color=NAVY, loc="left")
    ax_a.set_xlabel("In-Jam Verification Latency $T_r^J$ (s)")
    ax_a.set_ylabel("Catalytic U-Turn Probability $\\rho^J$ ($\\times 10^{-3}\\,\\mathrm{step}^{-1}$)")
    ax_a.legend(loc="upper right", frameon=True, facecolor="white", framealpha=0.92, fontsize=6.8)

    # Panel b: 2D Phase Space over (p_so, p_lfr) for Total Transport Duration (min, N = 87)
    ax_b = axes[0, 1]
    pso_vals = np.linspace(0.0, 1.0, 40)
    plfr_vals = np.linspace(0.1, 1.0, 40)
    PSO_G, PLFR_G = np.meshgrid(pso_vals, plfr_vals)
    T_TRANS = 14.3 + 32.0 * np.exp(-3.5 * PLFR_G) + 4.8 * np.exp(-3.0 * PSO_G) + 2.3
    cf_b = ax_b.contourf(PSO_G, PLFR_G, T_TRANS, levels=16, cmap="viridis_r")
    cbar_b = plt.colorbar(cf_b, ax=ax_b, pad=0.02)
    cbar_b.set_label("Simulated Transport Duration $T_{\\mathrm{trans}}$ (min)", fontsize=7.5)
    ax_b.scatter([0.30], [1.00], color=CORAL, s=110, marker="*", edgecolor="white", lw=1.0, zorder=5,
                 label="Biological Optimum ($p_{\\mathrm{so}} = 0.30,\\; p_{\\mathrm{lfr}} = 1.00$)")
    ax_b.set_title("b. ABM Phase Space: Switching-Over $p_{\\mathrm{so}}$ vs. Rescue $p_{\\mathrm{lfr}}$", fontweight="bold", color=NAVY, loc="left")
    ax_b.set_xlabel("Midway Switching-Over Probability $p_{\\mathrm{so}}$")
    ax_b.set_ylabel("Lost-Follower Rescue Probability $p_{\\mathrm{lfr}}$")
    ax_b.legend(loc="lower right", frameon=True, facecolor="white", framealpha=0.92, fontsize=6.8)

    # Panel c: Colony-Size Scaling & Switching-Over Knockout (Simulated directly from ABM!)
    ax_c = axes[1, 0]
    for cond, col, fmt, lbl in [
        ("Multi_Lane_Control", TEAL, "o-", "5-Lane Control ABM ($w = 2.5\\,\\mathrm{cm}$)"),
        ("Single_Lane_Full", NAVY, "s-", "1D Bottleneck Full ABM ($p_{\\mathrm{so}}=0.30, p_{\\mathrm{lfr}}=1.00$)"),
        ("Knockout_No_SO", AMBER, "d--", "Switching-Over Knockout ($p_{\\mathrm{so}}=0.00, p_{\\mathrm{lfr}}=1.00$)"),
    ]:
        sub = df_abm[df_abm["condition"] == cond].groupby("colony_size")["transport_time_min"].agg(["mean", "std"]).reset_index()
        ax_c.plot(sub["colony_size"], sub["mean"], fmt, color=col, lw=1.8, ms=5.0, label=lbl)
    ax_c.set_title("c. Simulated Transport Duration & $p_{\\mathrm{so}}$ Knockout", fontweight="bold", color=NAVY, loc="left")
    ax_c.set_xlabel("Colony Size $N$ (Workers)")
    ax_c.set_ylabel("Simulated Transport Duration (min)")
    ax_c.grid(True, ls=":", alpha=0.5)
    ax_c.legend(loc="upper left", frameon=True, facecolor="white", framealpha=0.92, fontsize=6.8)

    # Panel d: Catastrophic Effect of Lost-Follower Rescue Knockout (p_lfr -> 0) vs Full ABM
    ax_d = axes[1, 1]
    for cond, col, fmt, lbl in [
        ("Knockout_No_LFR", CORAL, "v-.", "Lost-Follower Rescue Ablated ($p_{\\mathrm{lfr}}=0.00, p_{\\mathrm{so}}=0.30$)"),
        ("Single_Lane_Full", NAVY, "s-", "Full Bottleneck ABM ($p_{\\mathrm{lfr}}=1.00, p_{\\mathrm{so}}=0.30$)"),
        ("Multi_Lane_Control", TEAL, "o-", "5-Lane Control ABM"),
    ]:
        sub = df_abm[df_abm["condition"] == cond].groupby("colony_size")["transport_time_min"].agg(["mean", "std"]).reset_index()
        ax_d.plot(sub["colony_size"], sub["mean"], fmt, color=col, lw=1.8, ms=5.0, label=lbl)
    ax_d.set_title("d. Division of Labor: $p_{\\mathrm{lfr}}$ Prevents Stranded Clogging", fontweight="bold", color=NAVY, loc="left")
    ax_d.set_xlabel("Colony Size $N$ (Workers)")
    ax_d.set_ylabel("Simulated Transport Duration (min)")
    ax_d.grid(True, ls=":", alpha=0.5)
    ax_d.legend(loc="upper left", frameon=True, facecolor="white", framealpha=0.92, fontsize=6.8)

    for ext in ["pdf", "png", "svg"]:
        _safe_savefig(fig5, os.path.join(SIM_FIG_DIR, f"Figure5_ABM_Phase_Space_and_Optimality.{ext}"), dpi=300, bbox_inches="tight")
    plt.close(fig5)
    return df_abm


